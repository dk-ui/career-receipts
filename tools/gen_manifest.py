#!/usr/bin/env python3
"""
Generates MANIFEST.md at the repo root by reading frontmatter (type/status/links)
across every .md file -- no prose-mining, no table-parsing. Also reports dead links
(frontmatter `links:` targets that don't resolve to a real file) and orphans (files
nothing else links to).

Run after adding/removing/moving files, or after editing frontmatter. See CLAUDE.md
"Frontmatter contract".
"""
import json
import os
import re
import subprocess
import sys
from typing import Optional

# repo root = parent of tools/. Derived, not hardcoded, so this runs on a CI
# runner and from any clone path.
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# examples/ holds a fictional sample vault. It must never show up in the owner's
# MANIFEST.md or counts, and its frontmatter is maintained by hand.
EXCLUDE_DIRS = {".git", "career-ops", "node_modules", "inbox", "examples"}

# files that are legitimately never linked to -- excluded from the orphan report
ORPHAN_EXEMPT = {"MANIFEST.md"}

STATUS_EMOJI = {"strong": "🟢", "partial": "🟡", "none": "🔴", "not-started": "⚪", None: "⚪"}

def parse_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end == -1:
        return {}, text
    fm_body = text[4:end]
    rest = text[end + 4:]
    fields = {}
    for line in fm_body.split("\n"):
        m = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip()
        if val.startswith("[") and val.endswith("]"):
            inner = val[1:-1].strip()
            fields[key] = [x.strip().strip('"\'') for x in inner.split(",") if x.strip()] if inner else []
        else:
            fields[key] = val
    return fields, rest

def count_gaps(body: str) -> int:
    return len(re.findall(r"^\s*-\s\[\s\]\s", body, re.MULTILINE))

def staged_markdown() -> dict[str, str]:
    """Every tracked .md file outside EXCLUDE_DIRS, as {path: content as git holds it}.

    Reads the git index, not the disk. MANIFEST.md is committed, and CI checks it on a
    clean checkout, so it has to describe what git will commit. Walking the disk counted
    untracked files and read unstaged edits, so any commit made with other uncommitted work
    around left a manifest that disagreed with the commit. New files appear once they are
    staged, which the pre-commit hook always is by the time it runs.
    """
    listing = subprocess.run(["git", "-C", ROOT, "ls-files", "-z", "--", "*.md"],
                             capture_output=True, text=True, check=True).stdout
    files: dict[str, str] = {}
    for relpath in filter(None, listing.split("\0")):
        folders = relpath.split("/")[:-1]
        if any(f in EXCLUDE_DIRS or f.startswith(".") for f in folders):
            continue
        files[relpath] = subprocess.run(["git", "-C", ROOT, "show", f":{relpath}"],
                                        capture_output=True, text=True, check=True).stdout
    return files


def main() -> int:
    nodes: dict[str, dict] = {}  # dir path -> info
    all_files: dict[str, dict] = {}  # relpath -> fields
    dead_links: list[tuple[str, str]] = []

    for relpath, text in staged_markdown().items():
        fields, body = parse_frontmatter(text)
        all_files[relpath] = fields

        if os.path.basename(relpath) == "README.md":
            d = os.path.dirname(relpath)
            nodes[d] = {
                "path": d or ".",
                "type": fields.get("type"),
                "status": fields.get("status"),
                "gaps": count_gaps(body),
            }

    # dead-link check across every file's `links:`, and inbound counts for orphan check
    tracked = set(subprocess.run(
        ["git", "-C", ROOT, "ls-files"],
        capture_output=True, text=True, check=True).stdout.splitlines())
    inbound: dict[str, int] = {relpath: 0 for relpath in all_files}
    for relpath, fields in all_files.items():
        for link in fields.get("links", []):
            if link.startswith(("http://", "https://", "mailto:")) or not link:
                continue
            # Resolve against git, not the filesystem. A link to a gitignored file
            # exists on your disk but in no clone or backup -- checking the disk
            # would call a link fine that is broken everywhere else.
            if link not in tracked:
                dead_links.append((relpath, link))
            elif link in inbound:
                inbound[link] += 1

    orphans = sorted(
        relpath for relpath, count in inbound.items()
        if count == 0 and relpath not in ORPHAN_EXEMPT and not relpath.endswith("CLAUDE.md")
    )

    # render MANIFEST.md
    lines = ["# MANIFEST.md — generated, do not hand-edit", "",
              f"Generated by `tools/gen_manifest.py` from frontmatter across {len(all_files)} "
              f"markdown files. Regenerate after structural changes.", ""]
    def sort_key(path):
        return () if path == "." else tuple(path.split("/"))

    for d in sorted(nodes.keys(), key=sort_key):
        n = nodes[d]
        depth = 0 if d == "." else d.count("/") + 1
        indent = "  " * depth
        flag = STATUS_EMOJI.get(n["status"], "⚪")
        tags = []
        if n["gaps"]:
            tags.append(f"gaps:{n['gaps']}")
        if n["type"]:
            tags.append(n["type"])
        tag_str = f" [{' '.join(tags)}]" if tags else ""
        lines.append(f"{indent}- {flag} `{n['path']}`{tag_str}")

    lines.append("")
    lines.append("## Dead links")
    if dead_links:
        lines.append("")
        for src, target in sorted(dead_links):
            lines.append(f"- `{src}` → `{target}` (missing)")
    else:
        lines.append("")
        lines.append("None.")

    lines.append("")
    lines.append("## Orphans")
    lines.append("")
    lines.append("Files nothing else links to -- not necessarily wrong (a fresh drop, or")
    lines.append("something only reachable via a folder link), but worth a look.")
    if orphans:
        lines.append("")
        for relpath in orphans:
            lines.append(f"- `{relpath}`")
    else:
        lines.append("")
        lines.append("None.")

    content = "\n".join(lines) + "\n"
    manifest_path = os.path.join(ROOT, "MANIFEST.md")

    # --check verifies instead of writing: catches anything committed with
    # --no-verify or from a clone where core.hooksPath was never set.
    if "--check" in sys.argv:
        try:
            with open(manifest_path) as f:
                current = f.read()
        except FileNotFoundError:
            current = None

        # Orphans are reported, never fatal -- a fresh drop is legitimately unlinked.
        if orphans:
            print(f"note: {len(orphans)} orphan(s), not a failure")
            for relpath in orphans:
                print(f"  - {relpath}")

        problems = []
        if current != content:
            problems.append("MANIFEST.md is stale -- run `python3 tools/gen_manifest.py`")
        problems += [f"dead link: {src} -> {target}" for src, target in sorted(dead_links)]

        if problems:
            print("\nMANIFEST CHECK FAILED:\n", file=sys.stderr)
            for problem in problems:
                print(f"  {problem}", file=sys.stderr)
            print("", file=sys.stderr)
            return 1

        print(f"manifest check clean — {len(nodes)} folder nodes, 0 dead links")
        return 0

    with open(manifest_path, "w") as f:
        f.write(content)

    if "--json" in sys.argv:
        print(json.dumps({"nodes": nodes, "dead_links": dead_links, "orphans": orphans}, indent=2))
    else:
        print(
            f"MANIFEST.md written — {len(nodes)} folder nodes, "
            f"{len(dead_links)} dead links, {len(orphans)} orphans"
        )
    return 0

if __name__ == "__main__":
    sys.exit(main())
